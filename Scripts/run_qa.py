"""Run every QA suite for the Nike Business Dashboard project and write Documentation/QA_Report.md.

Usage (from the project root):
    python Scripts/run_qa.py [--schemas <microsoft/json-schemas clone>] [--theme-schema <reportThemeSchema-*.json>]

Suites that need optional tools (Node.js, Playwright, the Microsoft schema repos) are reported as SKIPPED
when those tools are not available, never as PASS."""
import argparse, re, shutil, subprocess, sys, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PBI = ROOT / 'PowerBI'
ap = argparse.ArgumentParser()
ap.add_argument('--schemas'); ap.add_argument('--theme-schema'); ap.add_argument('--expected', default=str(ROOT / 'Scripts' / 'qa' / 'expected.json'))
a = ap.parse_args()

suites = []
def run(name, cmd, cwd=ROOT, need=None):
    if need and not need():
        suites.append((name, 'SKIPPED', [], 'required tool/schema not available'))
        return
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    lines = [l for l in (r.stdout + r.stderr).splitlines() if re.match(r'^(PASS|FAIL)', l)]
    status = 'PASS' if r.returncode == 0 and lines and not any(l.startswith('FAIL') for l in lines) else 'FAIL'
    suites.append((name, status, lines, (r.stdout + r.stderr)[-1500:] if status == 'FAIL' else ''))

py = sys.executable
bim = str(PBI / 'Nike_Business_Dashboard.SemanticModel' / 'model.bim')
run('1. Supplied dataset validator (Scripts/validate_dataset.py)', [py, 'Scripts/validate_dataset.py'])
run('2. Extended data-quality checks (Scripts/data_quality_checks.py)', [py, 'Scripts/data_quality_checks.py'])
run('3. Semantic model static checks: DAX references, M columns vs CSV headers, relationships, date table',
    [py, 'Scripts/qa/check_model.py', bim, str(ROOT / 'Data')])
run('4. Report layout checks: overlaps, containment, measure-bound cards', [py, 'Scripts/qa/layout_check.py'])
run('5. PBIR report vs official Microsoft Fabric JSON schemas + formatting catalogue + field bindings',
    [py, 'Scripts/qa/validate_pbir.py', str(PBI / 'Nike_Business_Dashboard.Report'), bim, str(a.schemas), str(a.theme_schema)],
    need=lambda: a.schemas and a.theme_schema and Path(a.schemas).exists() and Path(a.theme_schema).exists())
def theme_check():
    import json, jsonschema
    errs = list(jsonschema.Draft7Validator(json.loads(Path(a.theme_schema).read_text(encoding='utf-8'))).iter_errors(
        json.loads((PBI / 'Nike_Business_Theme.json').read_text(encoding='utf-8'))))
    return errs
if a.theme_schema and Path(a.theme_schema).exists():
    e = theme_check()
    suites.append(('6. Theme JSON vs official Power BI report-theme schema', 'PASS' if not e else 'FAIL',
                   [('PASS' if not e else 'FAIL') + f': Nike_Business_Theme.json valid against {Path(a.theme_schema).name}'], str(e[:3])))
else:
    suites.append(('6. Theme JSON vs official Power BI report-theme schema', 'SKIPPED', [], 'theme schema not supplied'))
run('7. Preview engine vs pandas reference values (independent re-implementation of the DAX)',
    ['node', 'Scripts/qa/engine_test.js', str(ROOT / 'Dashboard_Preview' / 'assets'), a.expected],
    need=lambda: shutil.which('node') and Path(a.expected).exists())
def has_playwright():
    try:
        import playwright  # noqa
        return True
    except ImportError:
        return False
run('8. HTML preview driven in Chromium (slicers, reset, cross-filter, drill-through, navigation) vs pandas',
    [py, 'Scripts/qa/ui_test.py', (ROOT / 'Dashboard_Preview' / 'index.html').as_uri(), str(ROOT / 'Data')], need=has_playwright)
run('9. Standalone single-file preview (same UI test, no assets folder)',
    [py, 'Scripts/qa/ui_test.py', (ROOT / 'Dashboard_Preview' / 'Nike_Dashboard_Preview_Standalone.html').as_uri(), str(ROOT / 'Data')], need=has_playwright)

# ---- structural presence checks
req = ['Data/Products.csv', 'Data/Customers.csv', 'Data/Stores.csv', 'Data/Sales.csv', 'Data/Marketing_Campaigns.csv', 'Data/Inventory.csv',
       'Data/Sustainability.csv', 'Data/Data_Dictionary.csv', 'PowerBI/Nike_Business_Theme.json', 'PowerBI/Power_Query_M_Code.txt',
       'PowerBI/DAX_Measures.txt', 'PowerBI/Data_Model.md', 'PowerBI/Dashboard_Layout.md', 'PowerBI/Nike_Business_Dashboard.pbip',
       'Scripts/validate_dataset.py', 'Dashboard_Preview/index.html', 'Documentation/Data_Quality_Report.md', 'Documentation/README.md']
missing = [r for r in req if not (ROOT / r).exists()]
suites.append(('10. Required deliverables present', 'PASS' if not missing else 'FAIL',
               [('PASS' if (ROOT / r).exists() else 'FAIL') + f': {r}' for r in req], ', '.join(missing)))

total = sum(len(s[2]) for s in suites)
passed = sum(1 for s in suites for l in s[2] if l.startswith('PASS'))
L = ['# QA Report - Nike Business Dashboard', '', f'Run: {datetime.datetime.now():%Y-%m-%d %H:%M}  ·  generated by `Scripts/run_qa.py`', '',
     f'**{passed} / {total} automated checks passed** across {len(suites)} suites. '
     f'Suites: {sum(s[1] == "PASS" for s in suites)} PASS, {sum(s[1] == "FAIL" for s in suites)} FAIL, {sum(s[1] == "SKIPPED" for s in suites)} SKIPPED.', '',
     '| Suite | Result | Checks |', '|---|---|---|']
L += [f'| {n} | **{st}** | {sum(l.startswith("PASS") for l in ls)}/{len(ls)} |' for n, st, ls, _ in suites]
L += ['', '## Items that cannot be verified automatically here', '',
      '| Item | Status | Notes |', '|---|---|---|',
      '| Native .pbix file | **NOT PRODUCED** | A .pbix stores a compressed, proprietary data model that only Power BI Desktop (Windows) writes. This build environment is Linux without Power BI Desktop, so the report is delivered as a native Power BI Project (.pbip). Open it in Desktop, refresh, then File > Save as > .pbix. |',
      '| Opening the .pbip in Power BI Desktop | **NOT RUN** | Every report file passes Microsoft\'s published schemas and the model passes static checks, but the project was not opened in Desktop here. Desktop re-validates on open and reports any problem by file. |',
      '| DAX executed by the Power BI engine | **NOT RUN** | DAX references and syntax structure are checked statically; results are cross-checked through an independent JavaScript implementation of the same measures (suite 7). |',
      '| "Clear all slicers" button action | **VERIFY ON OPEN** | Uses visualLink type `ClearAllSlicers`, which is not enumerated in the public schema. If Desktop shows the button as inactive, select it and set Action > Type = Clear all slicers. |',
      '| Visual-level K format on the Overview campaign table | **VERIFY ON OPEN** | Budget and attributed revenue use a visual-scoped format string `$#,0,"K"` (schema property `format`). If ignored, values show in full dollars. |',
      '| Labels / overlap in rendered Power BI visuals | **REVIEWED IN PREVIEW** | All 11 pages were rendered in the HTML preview at 1600x900 and reviewed; layout geometry is shared with the PBIR report (suite 4 checks overlaps). |', '']
for n, st, ls, det in suites:
    L += [f'## {n}', '', f'Result: **{st}**', '']
    L += [f'- {l}' for l in ls] or ['- ' + det]
    if st == 'FAIL' and det:
        L += ['', '```', det, '```']
    L.append('')
(ROOT / 'Documentation' / 'QA_Report.md').write_text('\n'.join(L), encoding='utf-8')
print(f'{passed}/{total} checks passed; suites:', ', '.join(f'{n.split(".")[0]}={st}' for n, st, _, _ in suites))
sys.exit(0 if all(s[1] in ('PASS', 'SKIPPED') for s in suites) else 1)
